#!/usr/bin/env python3
"""Local Wazuh 4.7.5 storage policy. No network, packages, or index operations."""
import argparse
from contextlib import contextmanager
import datetime as dt
import json
import os
from pathlib import Path
import re
import stat
import sys

KEEP_DAYS = 7
MONTHS = ('Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec')
SETTINGS = {'monitord.rotate_log': 1, 'monitord.keep_log_days': 7,
            'monitord.size_rotate': 64, 'monitord.daily_rotations': 4, 'monitord.compress': 1}
# Only compressed logs and the unnumbered checksum files generated by sign_log.c.
ARTIFACT = re.compile(r'ossec-alerts-([0-9]{2})(?:-([0-9]{3}|[1-9][0-9]{3,}))?\.(json|log)\.(gz|sum)\Z')
DIRECTORY_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW


def internal_options(content):
    """Replace only our keys, preserving all unrelated lines byte for byte."""
    output = []
    seen = set()
    for line in content.splitlines(keepends=True):
        match = re.match(r'^\s*([^#=\s]+)\s*=', line)
        key = match.group(1) if match else None
        if key in SETTINGS:
            if key not in seen:
                output.append(f'{key}={SETTINGS[key]}\n')
                seen.add(key)
        else:
            output.append(line)
    for key, value in SETTINGS.items():
        if key not in seen:
            if output and not output[-1].endswith('\n'):
                output[-1] += '\n'
            output.append(f'{key}={value}\n')
    return ''.join(output)


@contextmanager
def directory(path, parent=None):
    """Pin directories and reject links, including every absolute-path ancestor."""
    if parent is not None:
        descriptor = os.open(path, DIRECTORY_FLAGS, dir_fd=parent)
    else:
        path = Path(path)
        if not path.is_absolute() or '..' in path.parts:
            raise ValueError('An absolute contained directory is required')
        descriptor = os.open('/', DIRECTORY_FLAGS)
        try:
            for component in path.parts[1:]:
                child = os.open(component, DIRECTORY_FLAGS, dir_fd=descriptor)
                os.close(descriptor)
                descriptor = child
        except BaseException:
            os.close(descriptor)
            raise
    try:
        yield descriptor
    finally:
        os.close(descriptor)


def artifact_date(relative):
    parts = Path(relative).parts
    if len(parts) != 3 or str(Path(relative)) != relative:
        raise ValueError('Invalid generated alert path')
    year, month, filename = parts
    match = ARTIFACT.fullmatch(filename)
    if not re.fullmatch(r'[0-9]{4}', year) or month not in MONTHS or not match:
        raise ValueError('Invalid generated alert path')
    day, counter, _, extension = match.groups()
    if counter is not None and (int(counter) < 1 or extension != 'gz'):
        raise ValueError('Invalid generated alert suffix')
    return dt.date(int(year), MONTHS.index(month) + 1, int(day))


def fingerprint(info):
    return {key: getattr(info, 'st_' + key) for key in ('dev', 'ino', 'size', 'mtime_ns', 'ctime_ns')}


def eligible(relative, info, today):
    cutoff = today - dt.timedelta(days=KEEP_DAYS)
    # Date filenames are Wazuh local calendar dates; mtime adds a conservative
    # second guard against deleting a recently touched artifact with an old name.
    midnight = dt.datetime.combine(cutoff, dt.time()).timestamp()
    return (artifact_date(relative) < cutoff and stat.S_ISREG(info.st_mode)
            and info.st_nlink == 1 and info.st_mtime < midnight)


def plan_cleanup(manager_root, today=None):
    """Inspect only logs/alerts/YYYY/Mon. Never follow links or read log contents."""
    today = today or dt.date.today()
    result = []
    with directory(Path(manager_root) / 'logs/alerts') as base:
        for year in sorted(os.listdir(base)):
            if not re.fullmatch(r'[0-9]{4}', year):
                continue
            try:
                with directory(year, base) as year_fd:
                    for month in sorted(os.listdir(year_fd)):
                        if month not in MONTHS:
                            continue
                        try:
                            with directory(month, year_fd) as month_fd:
                                for filename in sorted(os.listdir(month_fd)):
                                    relative = f'{year}/{month}/{filename}'
                                    try:
                                        info = os.stat(filename, dir_fd=month_fd, follow_symlinks=False)
                                        if eligible(relative, info, today):
                                            result.append({'path': relative, **fingerprint(info)})
                                    except (ValueError, FileNotFoundError):
                                        continue
                        except (NotADirectoryError, FileNotFoundError, OSError) as error:
                            if error.errno not in (2, 20, 40):
                                raise
            except (NotADirectoryError, FileNotFoundError, OSError) as error:
                if error.errno not in (2, 20, 40):
                    raise
    return sorted(result, key=lambda item: item['path'])


def apply_cleanup(manager_root, plan, *, approved=False, today=None):
    """Delete only reviewed candidates whose identities still match the plan."""
    if approved is not True:
        raise ValueError('Cleanup requires apply_approved: true')
    if not isinstance(plan, list):
        raise ValueError('A reviewed candidate plan is required')
    today = today or dt.date.today()
    for row in plan:
        if not isinstance(row, dict) or set(row) != {'path', 'dev', 'ino', 'size', 'mtime_ns', 'ctime_ns'}:
            raise ValueError('Invalid cleanup plan')
        artifact_date(row['path'])
    removed = []
    with directory(Path(manager_root) / 'logs/alerts') as base:
        for row in plan:
            year, month, filename = Path(row['path']).parts
            try:
                with directory(year, base) as year_fd, directory(month, year_fd) as month_fd:
                    info = os.stat(filename, dir_fd=month_fd, follow_symlinks=False)
                    if (eligible(row['path'], info, today)
                            and all(row[key] == value for key, value in fingerprint(info).items())):
                        os.unlink(filename, dir_fd=month_fd)
                        removed.append(row['path'])
            except OSError as error:
                if error.errno not in (2, 20, 40):
                    raise
    return removed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    commands.add_parser('render', help='render internal options from stdin; no filesystem access')
    cleanup = commands.add_parser('cleanup', help='plan dated compressed alert cleanup as JSON')
    cleanup.add_argument('--apply-reviewed-plan', action='store_true', help='read boolean approval and plan JSON on stdin')
    cleanup.add_argument('--daily-approved', action='store_true', help='scheduled mode: plan before applying; requires stdin approval')
    args = parser.parse_args()
    if args.command == 'render':
        sys.stdout.write(internal_options(sys.stdin.read()))
        return
    if os.geteuid() != 0:
        raise ValueError('Cleanup must run as root')
    if args.apply_reviewed_plan and args.daily_approved:
        raise ValueError('Choose exactly one apply mode')
    manager = Path('/var/ossec')  # Deliberately no CLI path override.
    if args.apply_reviewed_plan or args.daily_approved:
        request = json.load(sys.stdin)
        if not isinstance(request, dict) or request.get('apply_approved') is not True:
            raise ValueError('Cleanup requires apply_approved: true')
        plan = plan_cleanup(manager) if args.daily_approved else request.get('plan')
        removed = apply_cleanup(manager, plan, approved=request['apply_approved'])
        print(json.dumps({'changed': bool(removed), 'removed': removed}))
    else:
        print(json.dumps({'changed': False, 'plan': plan_cleanup(manager)}))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError) as error:
        # Do not echo request/config contents or a traceback.
        print(f'Wazuh storage operation refused: {type(error).__name__}', file=sys.stderr)
        sys.exit(1)
